"""Turn Python functions into ordinary Supabase Edge Functions.

A project keeps each function's Python in <source>/<name>/ with a main.py that
defines `app`. Building writes supabase/functions/<name>/: a generated TypeScript
shim, the runtime, the Python files, and for Pyodide a memory snapshot. It also
sets the function's entry in supabase/config.toml.
"""

from __future__ import annotations

import base64
import gzip
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

import tomlkit

from supie import __version__, runtimes

BUNDLE_LIMIT = 20 * 2**20  # Supabase's limit on a function's bundled size
GENERATED = "// Generated by supie"
NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")
SKIP_DIRS = {
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    "node_modules",
}
SKIP_FILES = {"conftest.py", "requirements.txt", "supie.toml"}
RUNTIME_MODULES = ("__init__.py", "app.py", "supabase.py", "flow.py", "onnx.py")
STUBS = ("typing.py", "__future__.py")  # for MicroPython, which lacks both
DENO = "deno@2.9.6"


class BuildError(Exception):
    """A function can't be built; the message says why and what to do."""


@dataclass
class Function:
    """One function: its name, Python source folder and build settings."""

    name: str
    source: Path
    runtime: str = "micropython"
    verify_jwt: bool = True
    heap_mb: int = 16
    preload: list[str] = field(default_factory=list)

    @property
    def requirements(self) -> list[str]:
        """The packages in requirements.txt, without comments or blank lines."""
        path = self.source / "requirements.txt"
        if not path.is_file():
            return []
        lines = (
            line.split("#", 1)[0].strip() for line in path.read_text().splitlines()
        )
        return [line for line in lines if line]


@dataclass
class Project:
    """Where the Python functions and the Supabase project live."""

    root: Path
    source: Path
    supabase: Path
    functions: dict[str, Function]


@dataclass
class Report:
    """What a build produced."""

    function: Function
    out: Path
    size: int
    snapshot_cached: bool | None = None

    @property
    def over_limit(self) -> bool:
        """Whether the output, compressed, is likely over Supabase's bundle limit."""
        return self.size > BUNDLE_LIMIT


def load_project(root: Path) -> Project:
    """Read supie.toml (optional) and find every <source>/<name>/main.py."""
    root = root.resolve()
    config: dict = {}
    path = root / "supie.toml"
    if path.is_file():
        config = tomlkit.parse(path.read_text()).unwrap()
    settings = config.get("project", {})
    source = root / settings.get("source", "py")
    supabase = root / settings.get("supabase", "supabase")
    overrides = config.get("functions", {})

    functions = {}
    if source.is_dir():
        for main in sorted(source.glob("*/main.py")):
            name = main.parent.name
            functions[name] = _function(name, main.parent, overrides.get(name, {}))
    for name in overrides:
        if name not in functions:
            raise BuildError(
                f"supie.toml configures {name}, but {source / name / 'main.py'} doesn't exist"
            )
    return Project(root, source, supabase, functions)


def _function(name: str, source: Path, settings: dict) -> Function:
    """Build a Function from its folder and its supie.toml settings, checking them."""
    if not NAME.match(name):
        raise BuildError(
            f"{name!r} isn't a valid function name: use letters, digits, - and _"
        )
    unknown = set(settings) - {"runtime", "verify_jwt", "heap_mb", "preload"}
    if unknown:
        raise BuildError(
            f"unknown settings for {name} in supie.toml: {', '.join(sorted(unknown))}"
        )
    function = Function(name, source, **settings)
    if function.runtime not in runtimes.RUNTIMES:
        raise BuildError(
            f"{name}: runtime must be one of {', '.join(runtimes.RUNTIMES)}"
        )
    if function.requirements and function.runtime != "pyodide":
        raise BuildError(
            f"{name} has a requirements.txt, and packages need the pyodide runtime: "
            f'set runtime = "pyodide" under [functions.{name}] in supie.toml'
        )
    return function


def collect_files(
    source: Path, runtime: str = "micropython"
) -> tuple[dict[str, str], dict[str, bytes]]:
    """The function's files to ship, as text and binary, without tests or caches."""
    text: dict[str, str] = {}
    binary: dict[str, bytes] = {}
    for path in sorted(source.rglob("*")):
        rel = path.relative_to(source)
        if any(part in SKIP_DIRS or part.startswith(".") for part in rel.parts):
            continue
        if not path.is_file() or path.suffix == ".pyc" or path.name in SKIP_FILES:
            continue
        if path.name.startswith("test_") or path.name.endswith("_test.py"):
            continue
        data = path.read_bytes()
        try:
            text[rel.as_posix()] = data.decode()
        except UnicodeDecodeError:
            binary[rel.as_posix()] = data
    for name in RUNTIME_MODULES:
        text[f"supie/{name}"] = resources.files("supie").joinpath(name).read_text()
    if runtime == "micropython":
        for name in STUBS:
            if name not in text:
                stub = resources.files("supie").joinpath("stubs").joinpath(name)
                text[name] = stub.read_text()
    return text, binary


def _template(name: str, **values: object) -> str:
    """Read a template and fill in its __PLACEHOLDERS__."""
    text = resources.files("supie").joinpath("templates").joinpath(name).read_text()
    for key, value in {"VERSION": __version__, **values}.items():
        text = text.replace(f"__{key}__", str(value))
    return text


def _app_module(text: dict[str, str], binary: dict[str, bytes]) -> str:
    """The generated app.ts: the Python files as string literals."""
    lines = [f"{GENERATED} {__version__}. The function's Python files.", ""]
    lines.append('export const entry = "main";')
    lines.append("export const files: Record<string, string> = {")
    lines += [f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in text.items()]
    lines.append("};")
    lines.append("export const binaryFiles: Record<string, string> = {")
    lines += [
        f"  {json.dumps(k)}: {json.dumps(base64.b64encode(v).decode())},"
        for k, v in binary.items()
    ]
    lines.append("};")
    return "\n".join(lines) + "\n"


def _deno() -> list[str]:
    """How to run Deno: from PATH, or through npx without installing it."""
    if shutil.which("deno"):
        return ["deno"]
    if shutil.which("npx"):
        return ["npx", "-y", DENO]
    raise BuildError(
        "the pyodide runtime needs Deno to build its snapshot: install Deno or Node.js"
    )


def _tail(text: str, lines: int = 15) -> str:
    """The last lines of a tool's output, where the error usually is."""
    return "\n".join(text.strip().splitlines()[-lines:])


def packages(function: Function, runtime_dir: Path) -> Path | None:
    """Install requirements.txt into a zip, or reuse a cached one; None without requirements.

    Pin versions in requirements.txt: an unpinned one resolves to the newest
    release on the first build and stays cached after.
    """
    requirements = function.requirements
    if not requirements:
        return None
    runtime = runtimes.RUNTIMES["pyodide"]
    digest = hashlib.sha256(runtime.version.encode())
    digest.update(_template("install_packages.ts").encode())
    digest.update("\n".join(requirements).encode())
    cached = runtimes.cache_dir() / "packages" / f"{digest.hexdigest()[:24]}.zip"
    if cached.is_file():
        return cached
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        script = work / "install_packages.ts"
        script.write_text(_template("install_packages.ts"))
        out = work / "packages.zip"
        command = _deno() + [
            "run",
            "-A",
            str(script),
            str(runtime_dir),
            runtime.cdn,
            str(out),
            json.dumps(requirements),
        ]
        result = subprocess.run(command, capture_output=True, text=True, cwd=work)
        if result.returncode != 0 or not out.is_file():
            raise BuildError(
                f"{function.name}: installing {', '.join(requirements)} failed. Packages "
                f"must be pure Python or built by Pyodide.\n{_tail(result.stderr)}"
            )
        cached.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(out, cached)
    return cached


# Lets python_pyodide.ts load a compiled extension at the memory and table
# position it had when the snapshot was taken, and records where each one
# lands so make_snapshot.ts can save it. Pinned to Pyodide's Emscripten output.
PYODIDE_PATCHES = [
    (
        "var memoryBase=metadata.memorySize?alignMemory(getMemory(metadata.memorySize"
        "+memAlign),memAlign):0;var tableBase=metadata.tableSize?wasmTable.length:0;",
        "var supieForced=Module.supieForcedDylibs&&Module.supieForcedDylibs[libName];"
        "var memoryBase=supieForced?supieForced.memoryBase:(metadata.memorySize?"
        "alignMemory(getMemory(metadata.memorySize+memAlign),memAlign):0);"
        "var tableBase=supieForced?supieForced.tableBase:(metadata.tableSize?"
        "wasmTable.length:0);(Module.supieLoadedDylibs||=[]).push({name:libName,"
        "memoryBase,tableBase});",
    ),
    (
        "if(metadata.tableSize){wasmTable.grow(metadata.tableSize)}",
        "if(metadata.tableSize){if(supieForced){var supieGrow=tableBase+"
        "metadata.tableSize-wasmTable.length;if(supieGrow>0)wasmTable.grow(supieGrow)}"
        "else{wasmTable.grow(metadata.tableSize)}}",
    ),
]


def patch_pyodide(text: str) -> str:
    """Apply PYODIDE_PATCHES to pyodide.asm.mjs, failing if Pyodide's code changed."""
    for old, new in PYODIDE_PATCHES:
        if text.count(old) != 1:
            raise BuildError(
                "this Pyodide build doesn't match supie's snapshot patch; "
                "a newer supie may support it"
            )
        text = text.replace(old, new)
    return text


def copy_runtime(runtime: runtimes.Runtime, source: Path, target: Path) -> None:
    """Copy a runtime's files, patching Pyodide's loader."""
    target.mkdir(parents=True, exist_ok=True)
    for name in runtime.files:
        if runtime.name == "pyodide" and name == "pyodide.asm.mjs":
            (target / name).write_text(patch_pyodide((source / name).read_text()))
        else:
            shutil.copy2(source / name, target / name)


def snapshot(
    function: Function,
    runtime_dir: Path,
    packages_zip: Path | None = None,
    files: tuple[dict[str, str], dict[str, bytes]] | None = None,
) -> tuple[Path, bool]:
    """Build the Pyodide snapshot, or reuse a cached one; return its folder and whether it was cached.

    The folder holds snapshot.bin.gz, snapshot.json and dylibs/: the compiled
    extensions the preloads imported, which the function loads again before
    restoring. files are the function's own (from collect_files), so preload can
    name its modules; without them, only supie is in the snapshot.
    """
    if files is None:
        text = {
            f"supie/{name}": resources.files("supie").joinpath(name).read_text()
            for name in RUNTIME_MODULES
        }
        files = (text, {})
    runtime = runtimes.RUNTIMES["pyodide"]
    digest = hashlib.sha256(runtime.version.encode())
    for name, content in sorted(files[0].items()):
        digest.update(name.encode() + b"\0" + content.encode())
    for name, data in sorted(files[1].items()):
        digest.update(name.encode() + b"\0" + data)
    digest.update(_template("make_snapshot.ts").encode())
    digest.update(repr(PYODIDE_PATCHES).encode())
    digest.update(",".join(sorted(function.preload)).encode())
    if packages_zip is not None:
        digest.update(packages_zip.read_bytes())
    cached = runtimes.cache_dir() / "snapshots" / digest.hexdigest()[:24]
    if (cached / "snapshot.json").is_file():
        return cached, True

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        for name, content in files[0].items():
            (work / "app" / name).parent.mkdir(parents=True, exist_ok=True)
            (work / "app" / name).write_text(content)
        for name, data in files[1].items():
            (work / "app" / name).parent.mkdir(parents=True, exist_ok=True)
            (work / "app" / name).write_bytes(data)
        copy_runtime(runtime, runtime_dir, work / "runtime")
        script = work / "make_snapshot.ts"
        script.write_text(_template("make_snapshot.ts"))
        out = work / "out"
        command = _deno() + [
            "run",
            "-A",
            str(script),
            str(work / "runtime"),
            str(work / "app"),
            str(out),
            ", ".join(function.preload),
        ]
        if packages_zip is not None:
            command.append(str(packages_zip))
        result = subprocess.run(command, capture_output=True, text=True, cwd=work)
        if result.returncode != 0 or not (out / "snapshot.json").is_file():
            raise BuildError(
                f"{function.name}: building the Pyodide snapshot failed:\n"
                f"{_tail(result.stderr)}"
            )
        raw = out / "snapshot.bin"
        with (
            open(raw, "rb") as src,
            gzip.open(out / "snapshot.bin.gz", "wb", compresslevel=9) as dst,
        ):
            shutil.copyfileobj(src, dst)
        raw.unlink()
        partial = cached.with_name(cached.name + ".partial")
        shutil.rmtree(partial, ignore_errors=True)
        partial.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(out, partial)
        shutil.rmtree(cached, ignore_errors=True)
        partial.rename(cached)
    return cached, False


def build(project: Project, function: Function) -> Report:
    """Generate supabase/functions/<name>/ for one function."""
    if not (project.supabase / "config.toml").is_file():
        raise BuildError(
            f"no {project.supabase / 'config.toml'}: run `supabase init` first"
        )
    out = project.supabase / "functions" / function.name
    index = out / "index.ts"
    if out.exists() and not (
        index.is_file() and index.read_text().startswith(GENERATED)
    ):
        raise BuildError(
            f"{out} exists and wasn't generated by supie; rename one of them"
        )

    runtime = runtimes.RUNTIMES[function.runtime]
    runtime_dir = runtimes.fetch(runtime)
    text, binary = collect_files(function.source, function.runtime)

    shutil.rmtree(out, ignore_errors=True)
    (out / "runtime").mkdir(parents=True)
    copy_runtime(runtime, runtime_dir, out / "runtime")
    index.write_text(_template("index.ts", NAME=function.name))
    (out / "python.ts").write_text(
        _template(
            f"python_{function.runtime}.ts",
            RUNTIME_VERSION=runtime.version,
            HEAP_MB=function.heap_mb,
        )
    )
    (out / "app.ts").write_text(_app_module(text, binary))

    static = [f"./functions/{function.name}/runtime/*"]
    cached = None
    if function.runtime == "pyodide":
        (out / "compat.ts").write_text(_template("compat.ts"))
        zipped = packages(function, runtime_dir)
        own = {
            name.split("/")[0].removesuffix(".py")
            for name in [*text, *binary]
            if not name.startswith("supie/")
        }
        preloads_own = bool(own & {m.split(".")[0] for m in function.preload})
        folder, cached = snapshot(
            function, runtime_dir, zipped, (text, binary) if preloads_own else None
        )
        shutil.copytree(folder, out, dirs_exist_ok=True)
        if zipped is not None:
            _ship_packages(zipped, folder, out / "packages.zip")
            static.append(f"./functions/{function.name}/packages.zip")
        static += [
            f"./functions/{function.name}/snapshot.bin.gz",
            f"./functions/{function.name}/snapshot.json",
        ]
        if any((out / "dylibs").iterdir()):
            static.append(f"./functions/{function.name}/dylibs/*")
    _configure(project.supabase / "config.toml", function, static)
    return Report(function, out, compressed_size(out), cached)


def _ship_packages(zipped: Path, snapshot_dir: Path, target: Path) -> None:
    """Copy the packages zip, minus the extensions the snapshot restores itself."""
    import zipfile

    restored = set()
    for dylib in json.loads((snapshot_dir / "snapshot.json").read_text())["dylibs"]:
        _, _, rel = dylib["name"].partition("/site-packages/")
        restored.add(rel)
    if not restored:
        shutil.copy2(zipped, target)
        return
    with (
        zipfile.ZipFile(zipped) as src,
        zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as dst,
    ):
        for item in src.infolist():
            if item.filename not in restored:
                dst.writestr(item, src.read(item.filename))


def fingerprint(function: Function) -> tuple:
    """What a rebuild depends on in the source folder: every shipped file's mtime and size.

    Tests are left out, so editing them doesn't rebuild.
    """
    entries = []
    for path in sorted(function.source.rglob("*")):
        rel = path.relative_to(function.source)
        if any(part in SKIP_DIRS or part.startswith(".") for part in rel.parts):
            continue
        if not path.is_file() or path.suffix == ".pyc":
            continue
        if path.name.startswith("test_") or path.name.endswith("_test.py"):
            continue
        stat = path.stat()
        entries.append((rel.as_posix(), stat.st_mtime_ns, stat.st_size))
    return tuple(entries)


def compressed_size(folder: Path) -> int:
    """Roughly what Supabase counts against the bundle limit: each file gzipped."""
    total = 0
    for path in folder.rglob("*"):
        if path.is_file():
            data = path.read_bytes()
            packed = path.suffix in {".gz", ".zip"}
            total += len(data) if packed else len(gzip.compress(data, compresslevel=6))
    return total


def _configure(path: Path, function: Function, static: list[str]) -> None:
    """Set the function's verify_jwt and static_files in config.toml, keeping the rest."""
    doc = tomlkit.parse(path.read_text())
    if "functions" not in doc:
        doc["functions"] = tomlkit.table(is_super_table=True)
    functions = doc["functions"]
    entry = functions.get(function.name)
    if entry is None:
        entry = tomlkit.table()
        functions[function.name] = entry
    entry["verify_jwt"] = function.verify_jwt
    files = tomlkit.array()
    files.extend(static)
    files.multiline(True)
    entry["static_files"] = files
    path.write_text(tomlkit.dumps(doc))
