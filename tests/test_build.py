"""supie init and supie build on a throwaway project."""

import tomlkit
import pytest
from typer.testing import CliRunner

from supie import build
from supie.cli import app

runner = CliRunner()


def cli(*args):
    """Run the supie command and return the result."""
    return runner.invoke(app, [str(a) for a in args])


def test_init_creates_function(project):
    """init writes main.py and a test; the test passes under CPython."""
    result = cli("init", "hello", "--root", project)
    assert result.exit_code == 0, result.output
    folder = project / "py" / "hello"
    assert (folder / "main.py").is_file() and (folder / "test_main.py").is_file()
    assert "pytest" in result.output
    again = cli("init", "hello", "--root", project)
    assert again.exit_code == 1 and "already exists" in again.output


def test_init_rejects_bad_names(project):
    """Function names follow Supabase's rules."""
    assert cli("init", "9lives", "--root", project).exit_code == 1
    assert cli("init", "ok", "--runtime", "cpython", "--root", project).exit_code == 1


def test_init_pyodide_writes_settings(project):
    """Choosing pyodide records it in supie.toml."""
    cli("init", "heavy", "--runtime", "pyodide", "--root", project)
    config = tomlkit.parse((project / "supie.toml").read_text()).unwrap()
    assert config["functions"]["heavy"]["runtime"] == "pyodide"


@pytest.mark.network
def test_build_micropython(project):
    """build writes the shim, runtime and app files, and configures the function."""
    cli("init", "hello", "--root", project)
    (project / "py" / "hello" / "model.json").write_text('{"bins": [1, 2]}')
    (project / "py" / "hello" / "__pycache__").mkdir()
    (project / "py" / "hello" / "__pycache__" / "x.pyc").write_bytes(b"\0")
    result = cli("build", "--root", project)
    assert result.exit_code == 0, result.output
    assert "built hello (micropython)" in result.output

    out = project / "supabase" / "functions" / "hello"
    assert (out / "index.ts").read_text().startswith(build.GENERATED)
    assert (out / "runtime" / "micropython.wasm").is_file()
    app_ts = (out / "app.ts").read_text()
    assert (
        '"main.py"' in app_ts
        and '"model.json"' in app_ts
        and '"supie/app.py"' in app_ts
    )
    assert "test_main.py" not in app_ts and ".pyc" not in app_ts
    assert '"typing.py"' in app_ts and '"__future__.py"' in app_ts
    assert "heapsize: 16 * 2 ** 20" in (out / "python.ts").read_text()

    text = (project / "supabase" / "config.toml").read_text()
    assert text.startswith("# a comment supie must keep")
    config = tomlkit.parse(text).unwrap()
    assert config["functions"]["existing"] == {"verify_jwt": False}
    assert config["functions"]["hello"] == {
        "verify_jwt": True,
        "static_files": ["./functions/hello/runtime/*"],
    }

    rebuilt = cli("build", "hello", "--root", project)
    assert rebuilt.exit_code == 0, rebuilt.output


def test_build_refuses_hand_written_function(project):
    """A function supie didn't generate is never overwritten."""
    cli("init", "existing", "--root", project)
    hand = project / "supabase" / "functions" / "existing"
    hand.mkdir(parents=True)
    (hand / "index.ts").write_text("Deno.serve(() => new Response('mine'))\n")
    result = cli("build", "existing", "--root", project)
    assert result.exit_code == 1
    assert "wasn't generated by supie" in result.output
    assert (hand / "index.ts").read_text().startswith("Deno.serve")


def test_build_needs_supabase_project(tmp_path):
    """Without supabase/config.toml, build says to run supabase init."""
    cli("init", "hello", "--root", tmp_path)
    result = cli("build", "--root", tmp_path)
    assert result.exit_code == 1 and "supabase init" in result.output


def test_build_with_no_functions(project):
    """With nothing to build, build says how to create a function."""
    result = cli("build", "--root", project)
    assert result.exit_code == 1 and "supie init" in result.output


def test_supie_toml_validation(project):
    """Unknown settings, runtimes and missing folders are errors."""
    cli("init", "hello", "--root", project)
    toml = project / "supie.toml"
    toml.write_text("[functions.hello]\nmemory = 1\n")
    assert "unknown settings" in cli("build", "--root", project).output
    toml.write_text('[functions.hello]\nruntime = "cpython"\n')
    assert "runtime must be one of" in cli("build", "--root", project).output
    toml.write_text('[functions.ghost]\nruntime = "pyodide"\n')
    assert "doesn't exist" in cli("build", "--root", project).output


def test_integrity_check():
    """A tampered download fails verification."""
    from supie.runtimes import RUNTIMES, verify

    assert not verify(b"tampered", RUNTIMES["micropython"].integrity)


def test_flow_migration(project):
    """flow migration writes the tables' SQL once."""
    result = cli("flow", "migration", "--root", project)
    assert result.exit_code == 0, result.output
    (path,) = (project / "supabase" / "migrations").glob("*_supie_flows.sql")
    assert "create table if not exists public.supie_flow_runs" in path.read_text()
    again = cli("flow", "migration", "--root", project)
    assert again.exit_code == 1 and "already exists" in again.output


def test_requirements_need_pyodide(project):
    """A requirements.txt on a MicroPython function is refused with the fix."""
    cli("init", "hello", "--root", project)
    (project / "py" / "hello" / "requirements.txt").write_text("pydantic==2.12.5\n")
    result = cli("build", "--root", project)
    assert result.exit_code == 1
    assert 'runtime = "pyodide"' in result.output


def test_requirements_parsing(project):
    """Comments and blank lines in requirements.txt are ignored."""
    cli("init", "hello", "--runtime", "pyodide", "--root", project)
    (project / "py" / "hello" / "requirements.txt").write_text(
        "# models\npydantic==2.12.5  # compiled\n\nopenpyxl\n"
    )
    function = build.load_project(project).functions["hello"]
    assert function.requirements == ["pydantic==2.12.5", "openpyxl"]


def test_pyodide_patch_checks_the_code():
    """The snapshot patch refuses a Pyodide whose loader code differs."""
    with pytest.raises(build.BuildError, match="doesn't match"):
        build.patch_pyodide("var memoryBase=somethingElse;")
    old, new = build.PYODIDE_PATCHES[0]
    second_old, _ = build.PYODIDE_PATCHES[1]
    assert new in build.patch_pyodide(old + second_old)
